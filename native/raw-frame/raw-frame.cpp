template <typename T>
struct Ptr {
	T* p = nullptr;
	Ptr() = default;
	explicit Ptr(T* x) : p(x) {}
	~Ptr() {
		if (p) p->Release();
	}
	Ptr(const Ptr&) = delete;
	Ptr& operator=(const Ptr&) = delete;
	T* operator->() const { return p; }
	operator T*() const { return p; }
	T** out() { return &p; }
};

