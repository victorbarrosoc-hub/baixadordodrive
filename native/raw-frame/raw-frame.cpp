// ─────────── onde está a biblioteca ───────────

std::string pastaDoExecutavel() {
#if defined(_WIN32)
	wchar_t buf[MAX_PATH * 4];
	const DWORD n = GetModuleFileNameW(nullptr, buf, static_cast<DWORD>(std::size(buf)));
	if (n == 0) return {};
	std::wstring w(buf, n);
	w = w.substr(0, w.find_last_of(L"\\/"));
	const int len = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), static_cast<int>(w.size()), nullptr, 0, nullptr, nullptr);
	std::string out(len, '\0');
	WideCharToMultiByte(CP_UTF8, 0, w.c_str(), static_cast<int>(w.size()), out.data(), len, nullptr, nullptr);
	return out;
#elif defined(__APPLE__)
	uint32_t size = 0;
	_NSGetExecutablePath(nullptr, &size);
	std::string p(size, '\0');
	if (_NSGetExecutablePath(p.data(), &size) != 0) return {};
	p.resize(std::strlen(p.c_str()));
	return p.substr(0, p.find_last_of('/'));
#else
	char buf[4096];
	const ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
	if (n <= 0) return {};
	std::string p(buf, static_cast<size_t>(n));
	return p.substr(0, p.find_last_of('/'));
#endif
}

std::vector<std::string> pastasDaBiblioteca(const std::string& escolhida) {
	std::vector<std::string> out;
	if (!escolhida.empty()) out.push_back(escolhida);
	if (const char* env = std::getenv("SOBEDESCE_BRAW_LIB"); env && *env) out.emplace_back(env);
	const std::string aqui = pastaDoExecutavel();
	if (!aqui.empty()) out.push_back(aqui + "/BlackmagicRawAPI");
#if defined(_WIN32)
	for (const char* var : {"ProgramW6432", "ProgramFiles"}) {
		if (const char* pf = std::getenv(var); pf && *pf) {
			const std::string bd = std::string(pf) + "\\Blackmagic Design";
			out.push_back(bd + "\\Blackmagic RAW\\Blackmagic RAW SDK\\Win\\Libraries");
			out.push_back(bd + "\\Blackmagic RAW\\Blackmagic RAW Player");
			out.push_back(bd + "\\DaVinci Resolve");
		}
	}
#elif defined(__APPLE__)
	out.emplace_back("/Applications/Blackmagic RAW/Blackmagic RAW SDK/Mac/Libraries");
	out.emplace_back("/Library/Frameworks");
	out.emplace_back("/Applications/Blackmagic RAW/Blackmagic RAW Player.app/Contents/Frameworks");
	out.emplace_back("/Applications/DaVinci Resolve/DaVinci Resolve.app/Contents/Libraries");
#else
	out.emplace_back("/usr/lib64/blackmagic/BlackmagicRAWSDK/Linux/Libraries");
	out.emplace_back("/opt/resolve/libs");
#endif
	return out;
}

IBlackmagicRawFactory* abrirFabrica(const std::string& escolhida) {
	for (const auto& dir : pastasDaBiblioteca(escolhida)) {
		Texto t(dir);
		if (IBlackmagicRawFactory* f = CreateBlackmagicRawFactoryInstanceFromPath(t.v)) return f;
	}
	return nullptr;
}

